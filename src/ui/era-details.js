import { eraModel } from "../models/era.js";
import { formatRange, number, decimal } from "./format.js";

export function renderEraDetails(q, state, scene) {
  const { eraData: m, metrics, flux, daily } = scene;
  q("pbe-operating").textContent =
    `ЭРА · ${state.count} светильник(а) · ${m.watts * state.count} Вт номинально · 100% яркости. Диммирование не предусмотрено; регулируются высота, наклон и длительность работы.`;
  q("pbe-estimate-notice").textContent = m.ies
    ? "PPF и IES опубликованы ЭРА. Расчёт для распределённого источника: перенос IES на близкую крону — допущение. Это не измеренная карта PPFD."
    : `PPF опубликован ЭРА; форма пучка неизвестна. Диапазон — по трём предполагаемым углам 110° / 120° / 130°. Карта: база 120°, средний PPFD ≈ ${number(metrics.mean)}, DLI ≈ ${decimal(daily)}. Диапазон не является измеренной погрешностью.`;
  q("pbe-era-description").textContent =
    `${m.name} · ${m.cct}. PPF одного изделия: ${m.ppf} мкмоль/с; всех выбранных: ${flux} мкмоль/с. Значения изготовителя обозначены как расчётные, независимый протокол не найден.`;
  const rows = [
    [
      "PPF · опубликовано",
      `${m.ppf} мкмоль/с на светильник при номинальной работе. Не пересчитывается из электрических ватт. Допуск и изменение при нагреве неизвестны; они не включены в показанный диапазон.`,
    ],
    [
      "Питание · опубликовано",
      "Готовое сетевое изделие со встроенным питанием, без штатного DIM. Драйверы Samsung LCM/LDD к нему не применены; программный контроллер сам по себе не добавляет регулировку яркости.",
    ],
    [
      "Геометрия · допущение",
      m.geometry +
        " Высота — от центра принятой излучающей плоскости, не от патрона.",
    ],
    [
      "Несколько источников · компоновка",
      m.ies
        ? "Параллельные линейки, центры рядов через 160 мм. Каждый светильник получает свой полный PPF."
        : "Одна лампа по центру; две — центры через 360 мм; четыре — квадрат 360 × 360 мм. Положения проектные.",
    ],
  ];
  if (m.ies)
    rows.push(
      [
        "Пучок · файл изготовителя",
        "IES именно ФИТО-18W-PFR-GR: 10 C-плоскостей × 91 вертикальный угол. Сохранены различия между C-плоскостями и симметрия по четырём квадрантам. Протокол отдельного измерения этой модели не найден.",
      ],
      [
        "Полный поток · проверка",
        `Интеграл IES по всей сфере ≈ ${eraModel.curve.total.toFixed(3)} мкмоль/с; нормирован на паспортные 36. Около ${(100 * eraModel.curve.upwardFraction).toFixed(2)}% распределения находится позади источника (90–180°); этот поток не перенесён в передний пучок. Это характеристика файла, не потери мимо кроны.`,
      ],
      [
        "Ближнее поле · допущение",
        "Диаграмма всей линейки перенесена на равномерно распределённые элементы плоскости. C0 принят вдоль длинной стороны. На 20–50 см, сравнимых с длиной 57,5 см, такая модель требует проверки реальными замерами.",
      ],
      [
        "Проверка геометрии · другой расчёт",
        `Если каждую линейку заменить целиком точкой с тем же IES, при текущих настройках средний PPFD ≈ ${number(metrics.pointAlternative.mean)}, в центре ≈ ${number(metrics.pointAlternative.center)}; у распределённой модели ≈ ${number(metrics.mean)} и ≈ ${number(metrics.center)}. Это чувствительность к модели, не границы истинного значения.`,
      ],
    );
  else
    rows.push(
      [
        "Пучок · допущение",
        "IES не найден. В карточке указан угол 120°, но не раскрыто его определение. В модели он условно принят полным углом по половине максимума; осесимметричный cosⁿ-пучок, база — ламбертовый 120°.",
      ],
      [
        "Диапазон · чувствительность",
        `Сценарии 110° / 120° / 130°, каждый нормирован на тот же PPF ${m.ppf} мкмоль/с на изделие. Минимум–максимум по ним: средний PPFD ${formatRange(metrics.range.mean)}, центральный ${formatRange(metrics.range.center)}. 110° и 130° выбраны для проверки чувствительности, не являются паспортным допуском.`,
      ],
      [
        "Что диапазон не охватывает",
        "Разброс полного потока, нагрев, реальную объёмную колбу и её светораспределение. Для E27 25 Вт приближение плоским диском особенно условно. По известному PPF нельзя восстановить точную карту света.",
      ],
    );
  rows.push([
    "Общие ограничения",
    "Купол, комната, свет окна и затенение листьями не учтены. Отсутствие УФ/ИК у конкретного артикула не подтверждено. PPFD не определяет комфорт для человека или люксы на столе.",
  ]);
  q("pbe-era-table").replaceChildren(
    ...rows.map(([a, b]) => {
      const tr = document.createElement("tr");
      for (const value of [a, b]) {
        const td = document.createElement("td");
        td.textContent = value;
        tr.append(td);
      }
      return tr;
    }),
  );
  q("pbe-era-links").replaceChildren();
  const links = [
    ["Карточка ЭРА", m.url],
    ["Паспорт", m.passport],
  ];
  if (m.ies)
    links.push(
      ["IES · ЭРА", "https://www.eraworld.ru/download/items/info/193992"],
      ["Копия IES в расчёте", "./data/era/green-line-18.ies"],
    );
  for (const [i, [label, url]] of links.entries()) {
    if (i) q("pbe-era-links").append(" · ");
    const a = document.createElement("a");
    a.textContent = label;
    a.href = url;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    q("pbe-era-links").append(a);
  }
}
