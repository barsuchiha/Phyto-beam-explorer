import fs from "node:fs";
import { createHash } from "node:crypto";
import { parseQuadrantIES } from "../src/models/ies.js";

const bytes = fs.readFileSync(
  new URL("../data/era/green-line-18.ies", import.meta.url),
);
const data = parseQuadrantIES(bytes.toString("utf8"));
const metadata = {
  url: "https://www.eraworld.ru/download/items/info/193992",
  retrieved: "2026-11-12",
  sha256: createHash("sha256").update(bytes).digest("hex"),
  units: "micromol/s/sr, per the IES MORE note; not candela",
  ...data,
};
fs.writeFileSync(
  new URL("../src/data/era-ies.js", import.meta.url),
  "// Generated by node scripts/import-era-ies.mjs from the archived manufacturer file.\nexport const greenLineIES = " +
    JSON.stringify(metadata, null, 2) +
    ";\n",
);
