import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync, readdirSync, unlinkSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/models-light-worker.js"],
  bundle: true,
  write: false,
  minify: true,
  format: "esm",
  target: "es2020",
  legalComments: "eof",
});
const bytes = result.outputFiles[0].contents;
const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
const file = `light-${hash}.js`,
  dir = root + "data/workers/";
mkdirSync(dir, { recursive: true });
// Only generated worker bundles; old public copies may remain for cached pages.
for (const name of readdirSync(dir))
  if (/^light-[a-f0-9]{12}\.js$/.test(name) && name !== file)
    unlinkSync(dir + name);
writeFileSync(dir + file, bytes);
writeFileSync(
  root + "src/data/worker-asset.js",
  `// Generated by scripts/bundle-light-worker.mjs\nexport const lightWorkerFile = ${JSON.stringify(file)};\n`,
);
console.log(`Bundled light worker: ${file} (${bytes.length} bytes)`);
