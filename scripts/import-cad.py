"""Copy the project's existing CAD preview meshes; no CAD geometry regeneration.
Usage: python3 scripts/import-cad.py /path/to/concept-archive
Coordinates are quantized to 0.1 mm for a compact, self-contained web catalogue.
"""
import hashlib
import json
from pathlib import Path
import sys

archive = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out = root / 'data/cad'
out.mkdir(parents=True, exist_ok=True)

def pack(m):
    return {'name': m['name'], 'color': m['color'],
            'v': [round(x * 10) for p in m['vertices'] for x in p],
            't': [x for t in m['triangles'] for x in t]}

def center(m):
    return [(min(v[i] for v in m['vertices']) + max(v[i] for v in m['vertices'])) / 2 for i in range(3)]

entries = {}
def save(code, data, source):
    content = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    digest = hashlib.sha256(content.encode()).hexdigest()[:12]
    name = f'{code}-{digest}.json'
    (out / name).write_text(content)
    entries[code] = {'file': name, 'archive': source}
    print(code, len(content), 'bytes')

p00 = next(archive.glob('20_*')) / 'Исходники'
for code in ['A1', 'A2', 'B1', 'B2', 'B3', 'V2', 'V4', 'G2']:
    original = json.loads((p00 / f'{code}_mesh.json').read_text())
    result = []
    for pose, item in enumerate(original):
        # Detached and empty study poses cannot accept a working source.
        if (code == 'B3' and pose == 3) or (code == 'V2' and pose == 2):
            continue
        sources = []
        for i, m in enumerate(x for x in item['product'] if 'Light_output_placeholder' in x['name']):
            tilt = -90 if code == 'G2' else (15 if i == 0 else -15) if code == 'B1' and pose else 0
            sources.append({'center': center(m), 'tilt': tilt})
        result.append({'label': item['label'], 'meshes': [pack(m) for m in item['product']], 'sources': sources})
    save(code, result, f'{p00.parent.name}/Исходники/{code}_mesh.json')

soltech = next(archive.glob('21_*')) / 'Исходники'
for code, file in [('luna', '01_Luna'), ('stello', '02_Stello'), ('archetto', '03_Archetto'), ('pinocchio', '04_Pinocchio')]:
    original = json.loads((soltech / f'{file}_mesh.json').read_text())
    result = []
    for item in original:
        shell = next(m for m in item['context'] if 'pendant_shell' in m['name'])
        c = center(shell)
        anchor = [c[0], c[1], max(v[2] for v in shell['vertices']) + 16]
        result.append({'label': item['label'], 'meshes': [pack(m) for m in item['accessory'] + item['cord']], 'anchor': anchor, 'sources': []})
    save(code, result, f'{soltech.parent.name}/Исходники/{file}_mesh.json')

flex = next(archive.glob('22_*')) / 'Исходники'
item = json.loads((flex / 'meshes.json').read_text())[1]
sources = [{'center': center(m), 'tilt': 0} for m in item['fixed'] if 'light_output_placeholder' in m['name']]
save('B3flex', [{'label': 'Гибкий купол', 'meshes': [pack(m) for m in item['fixed']], 'sources': sources}], f'{flex.parent.name}/Исходники/meshes.json')
(root / 'src/data/cad-assets.js').write_text('/* Generated by scripts/import-cad.py. */\nexport const cadAssets = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n')
